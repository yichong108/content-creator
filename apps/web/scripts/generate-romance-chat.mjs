function flatten() {
  /** @type {Array<{kind: string; text: string}>} */
  const items = [];
  for (const session of sessions) {
    if (session.ts) {
      items.push({ kind: "timestamp", text: session.ts });
    }
    if (session.sys) {
      items.push({ kind: "system", text: session.sys });
    }
    for (const [who, text] of session.msgs) {
      items.push({
        kind: who === "in" ? "incoming" : "outgoing",
        text,
      });
    }
  }
  return items;
}

